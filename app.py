"""Provenance Guard — Flask backend.

Score convention: 0.0 = certainly human-written, 1.0 = certainly AI-generated.
See planning.md for the full flow.
"""

import json
import os
import re
import threading
import uuid
from datetime import datetime, timezone

from dotenv import load_dotenv
from flask import Flask, jsonify, request
from flask_limiter import Limiter
from flask_limiter.util import get_remote_address
from groq import Groq

load_dotenv()

app = Flask(__name__)
limiter = Limiter(
    get_remote_address,
    app=app,
    default_limits=[],          # only routes with an explicit @limiter.limit are limited
    storage_uri="memory://",    # fine for local dev; use redis:// if running multiple workers
)

# Rate limits (per client IP). Reasoning is documented in README.md.
SUBMIT_LIMIT = "10 per minute;100 per day"
APPEAL_LIMIT = "5 per minute;20 per day"

GROQ_MODEL = "qwen/qwen3.8-27b"
groq_client = Groq(api_key=os.getenv("GROQ_API_KEY"), timeout=15.0, max_retries=1)

LOG_PATH = "log.json"
MIN_SENTENCES = 4
LLM_WEIGHT = 0.7
STYLO_WEIGHT = 0.3
HUMAN_THRESHOLD = 0.35  # score < this -> likely_human
AI_THRESHOLD = 0.65     # score > this -> likely_ai

_log_lock = threading.Lock()


# ---------------------------------------------------------------------------
# Text processing
# ---------------------------------------------------------------------------

def text_handler(text):
    """Split raw text into a list of sentences."""
    parts = re.split(r"(?<=[.!?])\s+", text.strip())
    return [p.strip() for p in parts if p.strip()]


def length_filter(sentences):
    """True if there are enough sentences to score (>= MIN_SENTENCES)."""
    return len(sentences) >= MIN_SENTENCES


# ---------------------------------------------------------------------------
# Detection signals
# ---------------------------------------------------------------------------

LLM_SYSTEM_PROMPT = (
    "You are an AI-text detector. Given a piece of writing, estimate the "
    "probability that it was generated by an AI language model rather than "
    "written by a human. Use a scale where 0.0 means certainly human-written "
    "and 1.0 means certainly AI-generated. "
    "Be calibrated and use the whole scale. Short, plain, or formal writing "
    "(reviews, essays, news, meeting notes) is often human-written, and its style "
    "alone is weak evidence either way. Reserve scores below 0.15 or above 0.85 "
    "for text with strong, specific evidence (e.g. slang, typos and personal "
    "quirks for human; stacked cliches like 'delve', 'tapestry', 'in today's "
    "fast-paced world' for AI). When the evidence is mixed or the text is "
    "generic, answer between 0.35 and 0.65. "
    "Guide: 0.0-0.15 clearly human; 0.15-0.35 probably human; 0.35-0.65 "
    "uncertain; 0.65-0.85 probably AI; 0.85-1.0 clearly AI. "
    'Respond with JSON only, in exactly this form: {"score": <number between 0 and 1>}. '
    "Do not include any other keys, text, or explanation."
)


def llm_score(sentences):
    """Signal 1: ask the Groq-hosted LLM how likely the text is AI-generated.

    Returns a float in [0.0, 1.0], or None if the call fails for any reason
    (timeout, rate limit, network error, missing key, unparseable reply).
    """
    text = " ".join(sentences)
    try:
        completion = groq_client.chat.completions.create(
            model=GROQ_MODEL,
            messages=[
                {"role": "system", "content": LLM_SYSTEM_PROMPT},
                {"role": "user", "content": text},
            ],
            temperature=0,
            max_tokens=300,  # headroom for reasoning models that "think" before answering
            response_format={"type": "json_object"},
        )
        reply = completion.choices[0].message.content
        score = float(json.loads(reply)["score"])
    except Exception as e:  # any failure -> signal unavailable
        app.logger.warning("llm_score failed: %s", e)
        return None

    if score != score:  # NaN check
        return None
    return max(0.0, min(1.0, score))


def score_to_attribution(score):
    """Map a 0-1 score to a verdict using the thresholds in planning.md."""
    if score is None:
        return "uncertain"
    if score < HUMAN_THRESHOLD:
        return "likely_human"
    if score > AI_THRESHOLD:
        return "likely_ai"
    return "uncertain"


AI_PHRASES = [
    "delve", "delves", "delving", "tapestry", "testament to", "it's important to note",
    "it is important to note", "it's worth noting", "it is worth noting", "in today's",
    "ever-evolving", "ever-changing", "landscape", "realm", "navigate", "navigating",
    "foster", "fostering", "multifaceted", "pivotal", "crucial", "seamless", "seamlessly",
    "leverage", "leveraging", "robust", "holistic", "furthermore", "moreover",
    "in conclusion", "ultimately", "underscore", "underscores", "showcase", "showcasing",
    "a rich", "vibrant", "embark", "intricate", "nuanced", "paramount", "unlock",
    "harness", "elevate", "resonate", "resonates", "plays a vital role", "plays a crucial role",
]
_PHRASE_RE = re.compile(r"\b(?:" + "|".join(re.escape(p) for p in AI_PHRASES) + r")\b")
# "it's not X, it's Y" / "not just X, but Y" constructions
_NOT_X_BUT_Y_RE = re.compile(r"\b(?:it's|it is|this is|that's) not\b[^.!?]{1,60}?\b(?:it's|it is|but)\b|\bnot (?:just|only)\b[^.!?]{1,60}?\bbut\b")
_WORD_RE = re.compile(r"[a-z]+(?:['’][a-z]+)?")
_CONTRACTION_RE = re.compile(r"\b[a-z]+['’](?:t|s|re|ve|ll|d|m)\b")


def _clamp(x):
    return max(0.0, min(1.0, x))


def _phrase_bank_score(sentences):
    """min(1.0, AI-phrase hits / number of sentences)."""
    text = " ".join(sentences).lower().replace("’", "'")
    hits = len(_PHRASE_RE.findall(text)) + len(_NOT_X_BUT_Y_RE.findall(text))
    return min(1.0, hits / len(sentences))


def _length_uniformity_score(sentences):
    """Low variation in sentence length -> 1.0.

    Uses coefficient of variation (stdev / mean of words-per-sentence).
    CV <= 0.20 (very uniform) -> 1.0;  CV >= 0.70 (very irregular) -> 0.0; linear between.
    """
    lengths = [len(_WORD_RE.findall(s.lower())) for s in sentences]
    lengths = [n for n in lengths if n > 0]
    if len(lengths) < 2:
        return 0.5
    mean = sum(lengths) / len(lengths)
    stdev = (sum((n - mean) ** 2 for n in lengths) / len(lengths)) ** 0.5
    cv = stdev / mean
    return _clamp((0.70 - cv) / 0.50)


def _vocab_variety_score(sentences, window=50):
    """Low unique-words / total-words ratio -> 1.0.

    Plain type-token ratio drops as text gets longer, so we use a moving-average
    TTR over 50-word windows (MATTR) to keep short and long posts comparable.
    MATTR >= 0.85 -> 0.0;  MATTR <= 0.65 -> 1.0; linear between.
    """
    words = _WORD_RE.findall(" ".join(sentences).lower())
    if not words:
        return 0.5
    if len(words) <= window:
        mattr = len(set(words)) / len(words)
    else:
        ttrs = [len(set(words[i:i + window])) / window for i in range(len(words) - window + 1)]
        mattr = sum(ttrs) / len(ttrs)
    return _clamp((0.85 - mattr) / 0.20)


def _punctuation_score(sentences):
    """No contractions + heavy em-dash use -> 1.0 (optional sub-score in planning.md).

    Average of two halves:
      - contractions: 0 per sentence -> 1.0, >= 0.5 per sentence -> 0.0
      - em-dashes:    0 per sentence -> 0.0, >= 0.3 per sentence -> 1.0
    """
    text = " ".join(sentences)
    n = len(sentences)
    contractions = len(_CONTRACTION_RE.findall(text.lower().replace("’", "'")))
    dashes = text.count("—") + text.count(" -- ")
    no_contractions = _clamp(1.0 - (contractions / n) / 0.5)
    em_dash = _clamp((dashes / n) / 0.3)
    return (no_contractions + em_dash) / 2


def stylometric_breakdown(sentences):
    """Each sub-score on the 0-1 scale (1.0 = AI-like), plus their average."""
    subs = {
        "phrase_bank": _phrase_bank_score(sentences),
        "length_uniformity": _length_uniformity_score(sentences),
        "vocab_variety": _vocab_variety_score(sentences),
        "punctuation": _punctuation_score(sentences),
    }
    subs = {k: round(v, 3) for k, v in subs.items()}
    subs["score"] = round(sum(subs.values()) / len(subs), 3)
    return subs


def stylometric_score(sentences):
    """Signal 2: average of phrase bank, sentence-length uniformity, vocabulary
    variety, and punctuation sub-scores. Always returns a float in [0.0, 1.0]."""
    return stylometric_breakdown(sentences)["score"]


def combine_scores(llm, stylo):
    """final = 0.7*llm + 0.3*stylo; if llm is None, final = stylo."""
    if llm is None:
        return round(stylo, 3)
    return round(LLM_WEIGHT * llm + STYLO_WEIGHT * stylo, 3)


