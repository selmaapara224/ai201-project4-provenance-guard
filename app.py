@app.post("/submit")
@limiter.limit(SUBMIT_LIMIT)
def submit():
    data = request.get_json(silent=True)
    if not isinstance(data, dict):
        return jsonify({"error": "Request body must be a JSON object."}), 400

    missing = [
        field for field in ("text", "creator_id")
        if not isinstance(data.get(field), str) or not data[field].strip()
    ]
    if missing:
        return jsonify({"error": f"Missing or empty required field(s): {', '.join(missing)}"}), 400

    content_id = str(uuid.uuid4())
    creator_id = data["creator_id"]
    text = data["text"]

    sentences = text_handler(text)
    llm = stylo = combined = None
    if not length_filter(sentences):
        result = get_response(reason="length")
    else:
        llm = llm_score(sentences)
        stylo = stylometric_score(sentences)
        combined = combine_scores(llm, stylo)
        result = get_response(reason="score", score=combined)

    entry = {
        "content_id": content_id,
        "creator_id": creator_id,
        "timestamp": _now(),
        "text": text,
        "attribution": result["attribution"],
        "confidence": result["confidence"],
        "label": result["label"],
        "llm_score": llm,
        "stylo_score": stylo,
        "combined_score": combined,
        "llm_unavailable": llm is None and stylo is not None,
        "status": "classified",
    }
    add_to_log(entry)

    return jsonify({
        "content_id": content_id,
        "creator_id": creator_id,
        **result,
        "llm_score": llm,
        "stylo_score": stylo,
        "combined_score": combined,
        "llm_unavailable": entry["llm_unavailable"],
    }), 200


@app.post("/appeal")
@limiter.limit(APPEAL_LIMIT)
def appeal():
    data = request.get_json(silent=True)
    if not isinstance(data, dict):
        return jsonify({"error": "Request body must be a JSON object."}), 400

    missing = [
        field for field in ("content_id", "creator_reasoning")
        if not isinstance(data.get(field), str) or not data[field].strip()
    ]
    if missing:
        return jsonify({"error": f"Missing or empty required field(s): {', '.join(missing)}"}), 400

    outcome, entry = file_appeal(data["content_id"].strip(), data["creator_reasoning"].strip())
    if outcome == "not_found":
        return jsonify({"error": "No post with that ID exists."}), 404
    if outcome == "already_under_review":
        return jsonify({"error": "An appeal for this post is already under review."}), 409

    return jsonify({
        "message": "Your appeal has been submitted and is now under review.",
        "content_id": entry["content_id"],
        "status": entry["status"],
        "original_attribution": entry["attribution"],
        "original_confidence": entry["confidence"],
        "appeal_filed_at": entry["appeal_filed_at"],
    }), 200


@app.get("/log")
def log():
    """Most recent audit log entries (newest first). Optional ?limit=N (default 20, max 100).

    No auth — for documentation/grading visibility only; a real system would protect this.
    """
    limit = request.args.get("limit", default=20, type=int)
    limit = max(1, min(limit, 100))
    return jsonify({"entries": get_log(limit)})


@app.errorhandler(429)
def rate_limited(e):
    return jsonify({
        "error": "Too many requests. Please slow down.",
        "limit": str(e.description),  # e.g. "10 per 1 minute"
    }), 429


if __name__ == "__main__":
    app.run(debug=True, port=int(os.getenv("PORT", 5001)))  # 5000 is taken by macOS AirPlay
