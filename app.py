LABELS = {
    "likely_ai": (
        "Likely AI-generated: our system found strong signs that this text was "
        "written with an AI tool (AI-likelihood score: {pct}%). Automated detection "
        "can be wrong. If you wrote this yourself, you can appeal this result."
    ),
    "uncertain": (
        "Origin uncertain: we couldn't tell with confidence whether this text was "
        "written by a person or with an AI tool (AI-likelihood score: {pct}%). "
        "No action is taken based on this result."
    ),
    "likely_human": (
        "Likely human-written: our system found no strong signs of AI generation "
        "in this text (AI-likelihood score: {pct}%)."
    ),
}
TOO_SHORT_LABEL = (
    "Origin uncertain: this text is too short to analyze reliably (fewer than "
    f"{MIN_SENTENCES} sentences), so no AI-likelihood score was given."
)


def generate_label(score):
    """Map a 0-1 confidence score (or None) to the transparency label shown to users.

    < 0.35 -> likely_human, 0.35-0.65 -> uncertain, > 0.65 -> likely_ai.
    None (text too short) -> the too-short variant of the uncertain label.
    """
    if score is None:
        return TOO_SHORT_LABEL
    return LABELS[score_to_attribution(score)].format(pct=round(score * 100))


def get_response(reason, score=None):
    """Build the response dict ("length" -> uncertain/null, "score" -> threshold verdict)."""
    if reason == "length":
        return {
            "attribution": "uncertain",
            "confidence": None,
            "label": generate_label(None),
            "reason": f"Text too short to score (fewer than {MIN_SENTENCES} sentences).",
        }
    return {
        "attribution": score_to_attribution(score),
        "confidence": score,
        "label": generate_label(score),
    }


def _now():
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


def _read_log():
    """Return all log entries (oldest first), or [] if the log doesn't exist yet."""
    if not os.path.exists(LOG_PATH):
        return []
    with open(LOG_PATH) as f:
        return json.load(f)


def get_log(limit=20):
    """Return the most recent `limit` log entries, newest first."""
    with _log_lock:
        entries = _read_log()
    return entries[::-1][:limit]


def add_to_log(entry):
    """Append an entry to log.json (create if missing). Never overwrite/delete."""
    with _log_lock:
        entries = _read_log()
        entries.append(entry)
        _write_log(entries)


def find_post(content_id):
    """Return the log entry with this content_id, or None."""
    with _log_lock:
        entries = _read_log()
    return next((e for e in entries if e.get("content_id") == content_id), None)


def _write_log(entries):
    tmp_path = LOG_PATH + ".tmp"
    with open(tmp_path, "w") as f:
        json.dump(entries, f, indent=2)
    os.replace(tmp_path, LOG_PATH)  # atomic swap: a crash mid-write can't corrupt log.json


def file_appeal(content_id, reasoning):
    """Mark a post as under review and record the appeal on its log entry.

    The original classification fields are left untouched so the appeal sits
    alongside the decision it disputes. Returns ("ok" | "not_found" |
    "already_under_review", entry).
    """
    with _log_lock:
        entries = _read_log()
        entry = next((e for e in entries if e.get("content_id") == content_id), None)
        if entry is None:
            return "not_found", None
        if entry.get("status") == "under_review":
            return "already_under_review", entry
        entry["status"] = "under_review"
        entry["appeal_reasoning"] = reasoning
        entry["appeal_filed_at"] = _now()
        _write_log(entries)
        return "ok", entry


